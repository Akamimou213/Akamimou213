"""Compile every /science page into one file for Codex: science/SCIENCE_FULL.md.

Each page is copied verbatim (frontmatter + body) between markers:

    <!-- BEGIN FILE: science/evidence/fiber-and-constipation.md | ROUTE: /science/evidence/fiber-and-constipation -->
    ...
    <!-- END FILE: science/evidence/fiber-and-constipation.md -->

so Codex can either read it top to bottom or split it back into files.
Run after any page edit: python3 science/build_science_full.py
"""

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "SCIENCE_FULL.md"

ORDER = ["index.md", "how-our-ai-works.md", "gut-health-score.md", "clinical-review.md", "research.md", "evidence/index.md"]
TOPICS = [
    "bristol-stool-scale", "how-often-should-you-poop", "gut-transit-time", "fiber-and-constipation",
    "food-diaries-vs-memory", "lactose-intolerance", "gluten-without-celiac", "ibs-diet-guidelines",
    "stress-and-ibs", "post-infectious-ibs", "bloating-research", "gut-microbiome-tests", "ai-stool-and-meal-photos",
]
ORDER += [f"evidence/{t}.md" for t in TOPICS]


def front(text, key):
    m = re.search(rf"^{key}:\s*\"?([^\"\n#]+)", text, re.M)
    return m.group(1).strip() if m else ""


def main():
    pages = []
    for rel in ORDER:
        p = HERE / rel
        text = p.read_text(encoding="utf-8").rstrip() + "\n"
        pages.append((rel, front(text, "url"), front(text, "title"), front(text, "template"), text))
    missing = [t for t in TOPICS if not (HERE / "evidence" / f"{t}.md").exists()]
    if missing:
        raise SystemExit(f"missing topic pages: {missing}")

    head = ["# Get Regular /science: full page copy for Codex", "",
            "Generated by `science/build_science_full.py` from the files in `science/`. **Don't edit this file**; edit the source page and rebuild.", "",
            "## How to implement", "",
            "1. **Routes:** one page per block below, at the `ROUTE` in its marker. `/how-ai-works` → 301 to `/science/how-our-ai-works`.",
            "2. **Content source:** copy each block into `content/science/<path>.md` (split on the `BEGIN FILE` / `END FILE` markers) and render it with the same MDX/markdown loader as `/learn` (YAML frontmatter, `remark-gfm` tables).",
            "3. **Publish gate (same as the blog drafts):** render a page as `noindex` and keep it out of the sitemap until `review_status: approved`, a consenting clinician resolves in `medical_reviewer`, and `date_published` is set. Preview deployments show a \"DRAFT, needs medical review\" banner.",
            "4. **Templates:** `science-hub`, `science-trust-page`, `science-method-page`, `science-evidence-library` and `science-evidence-topic` (frontmatter `template`). Render the `> **Short answer:**` / `> **In short:**` blockquote as the answer box, at the top, in the server HTML.",
            "5. **Structured data:** follow the `<!-- JSON-LD: … -->` comment at the end of each page. `MedicalWebPage` + `citation[]` as `ScholarlyArticle` (PubMed URL in `sameAs`, DOI in `identifier`). Add `reviewedBy` and `lastReviewed` **only** when a clinician has approved the page and consented to be named. Reference `#org` and `#app` by `@id`.",
            "6. **Placeholders:** `[CONFIRM …]` and `[SET AT PUBLISH]` must be resolved or removed before a page can be approved. Don't render them in production; fail the build if one reaches a page marked `approved`.",
            "7. **Strip** `<!-- … -->` writer and JSON-LD comments from the rendered HTML; keep them in the source.",
            "8. **Evidence library table:** the block between `<!-- LIBRARY:START -->` and `<!-- LIBRARY:END -->` in `/science/evidence` is generated (`science/build_evidence_index.py`). Rebuild with `python3 science/build_evidence_library.py && python3 science/build_evidence_index.py` before each release; it flags retracted papers.",
            "9. **Links** point to `/learn/<slug>`, `/tools/<tool>` and `/resources/<asset>`. Until a target exists, render the link text without the link rather than linking to a 404.",
            "", "## Pages", "", "| # | Route | Title | Template |", "|---|---|---|---|"]
    for i, (rel, url, title, tpl, _) in enumerate(pages, 1):
        head.append(f"| {i} | `{url}` | {title} | `{tpl}` |")
    head += ["", "---", ""]

    body = []
    for rel, url, _, _, text in pages:
        body += [f"<!-- BEGIN FILE: science/{rel} | ROUTE: {url} -->", "", text, f"<!-- END FILE: science/{rel} -->", "", "---", ""]
    OUT.write_text("\n".join(head + body), encoding="utf-8")
    words = sum(len(t.split()) for *_, t in pages)
    print(f"wrote {OUT.name}: {len(pages)} pages, {words:,} words")


if __name__ == "__main__":
    main()
